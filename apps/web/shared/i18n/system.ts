const catalogs: Record<PlatformLocale, Record<SystemMessageKey, string>> = { 'zh-CN': zhCN, en }

const errorMessages: Record<string, SystemMessageKey> = {
  'identity.auth_required': 'error.auth_required',
  'identity.capability_forbidden': 'error.forbidden',
  'identity.email_unverified': 'error.email_unverified',
  'identity.registration_disabled': 'error.registration_disabled',
  'identity.invalid_credentials': 'error.invalid_credentials',
  'resource.version_conflict': 'error.version_conflict',
  'security.rate_limited': 'error.rate_limited',
}

export function isPlatformLocale(value: unknown): value is PlatformLocale {
  return value === 'zh-CN' || value === 'en'
}

export function systemMessage(
  locale: PlatformLocale,
  key: SystemMessageKey,
  values: Record<string, string | number> = {},
): string {
  return catalogs[locale][key].replace(/\{([a-z0-9_]+)\}/giu, (match, name: string) => (
    Object.hasOwn(values, name) ? String(values[name]) : match
  ))
}

export function systemStatus(locale: PlatformLocale, status: string): string {
  const key = `status.${status}` as SystemMessageKey
  return Object.hasOwn(catalogs[locale], key) ? catalogs[locale][key] : status
}

export function systemErrorMessage(locale: PlatformLocale, code: string | null | undefined): string {
  const key = code ? errorMessages[code] : undefined
  return systemMessage(locale, key ?? 'request.failed')
}

export function originalBusinessContent<T>(value: T): T {
  return value
}
